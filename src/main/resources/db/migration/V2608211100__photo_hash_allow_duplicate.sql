-- V2608211100: 같은 사진으로도 다시 등록할 수 있게 한다 (CATCHEAT-89)
--
-- V1이 photo.hash에 컬럼 레벨 UNIQUE를 걸어 "같은 사진 반복 등록"을 막고 있었다.
-- 그 규칙을 철회한다 — 같은 음식을 다시 먹고 같은 사진을 쓰는 것이 어뷰징이 아니고,
-- 전역 유일이라 **다른 사람이 먼저 올린 사진**까지 막고 있었다.
--
-- 컬럼 레벨 UNIQUE는 Postgres가 <테이블>_<컬럼>_key로 이름을 붙인다.
-- 이름이 다를 수 있어 IF EXISTS로 둔다 — 없으면 조용히 지나간다.
ALTER TABLE photo DROP CONSTRAINT IF EXISTS photo_hash_key;

-- hash 컬럼 자체는 남긴다. 이미 쌓인 값이 있고, 컬럼 정리는 이 값을 쓸 일이
-- 정말 없다는 것이 확인된 뒤에 한다.
