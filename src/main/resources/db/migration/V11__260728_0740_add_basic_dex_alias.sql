-- 칸 이름 오타 검증 — 매칭 안 되는 시드가 하나라도 있으면 멈춘다.
DO $$
DECLARE
    orphans TEXT;
BEGIN
    SELECT string_agg(DISTINCT s.name, ', ')
      INTO orphans
      FROM alias_seed s
      LEFT JOIN basic_dex d ON d.name = s.name
     WHERE d.id IS NULL;

    IF orphans IS NOT NULL THEN
        RAISE EXCEPTION '별칭 시드의 칸 이름이 basic_dex에 없습니다: %', orphans;
    END IF;
END $$;

INSERT INTO basic_dex_alias (basic_dex_id, alias)
SELECT d.id, s.alias
  FROM alias_seed s
  JOIN basic_dex d ON d.name = s.name;

