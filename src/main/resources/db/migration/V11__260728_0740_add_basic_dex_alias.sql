-- 도감 칸 별칭 사전 (PLAN.md "📖 기본 도감 200칸 (확정)" 구현 메모)
--
-- 별칭은 AI 분류 기준이 아니라 **유저 검색용 동의어 사전**이다.
-- 음식 이름은 도감 200칸 검색으로만 입력받으므로(자유 타이핑 금지), 표기 흔들림을
-- 새 칸으로 만들지 않고 전부 여기서 흡수한다. 초성 검색과 함께 등록 마찰을 줄이는 장치다.
--
-- alias는 전역 UNIQUE가 아니다. '냉면'은 물냉면·비빔냉면 두 칸에 모두 걸리고,
-- 검색은 두 칸을 다 돌려주는 것이 옳다. 단일 매칭을 강제하면 유저가 고를 기회를 잃는다.

CREATE TABLE basic_dex_alias (
    id BIGSERIAL PRIMARY KEY,
    basic_dex_id BIGINT NOT NULL,
    alias VARCHAR(100) NOT NULL,
    CONSTRAINT fk_basic_dex_alias_basic_dex FOREIGN KEY (basic_dex_id)
        REFERENCES basic_dex (id) ON DELETE CASCADE,
    CONSTRAINT uk_basic_dex_alias UNIQUE (basic_dex_id, alias)
);

CREATE INDEX idx_basic_dex_alias_alias ON basic_dex_alias (alias);

-- 시드는 임시 테이블을 거친다. 칸 이름을 잘못 적으면 JOIN에서 조용히 누락되는데,
-- 별칭이 몇 개 빠진 것은 테스트로 잡히지 않고 검색이 안 되는 형태로만 드러나기 때문이다.
CREATE TEMP TABLE alias_seed (name TEXT, alias TEXT);

